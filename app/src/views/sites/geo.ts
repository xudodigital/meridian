const inPoly = (x: number, y: number, p: Ring): boolean => {
  let c = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const a = p[i], b = p[j];
    if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) c = !c;
  }
  return c;
};

let landPath = '';
/** SVG path of a dot every 2.5 degrees that falls on land, in the map's 720 x 280 viewBox. Computed once. */
export function landDots(): string {
  if (landPath) return landPath;
  let d = '';
  for (let lat = 78; lat >= -56; lat -= 2.5) for (let lon = -170; lon <= 178; lon += 2.5) {
    if (LAND.some(p => inPoly(lon, lat, p))) { const x = (lon + 180) * 2, y = (80 - lat) * 2; d += `M${x - 1.8} ${y}a1.8 1.8 0 1 0 3.6 0a1.8 1.8 0 1 0-3.6 0`; }
  }
  return landPath = d;
}

